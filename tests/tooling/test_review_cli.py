"""Real CLI review, text export and obsolete argument rejection for both targets."""
import json
import os
from pathlib import Path
import subprocess
import sys

import pytest

ROOT = Path(__file__).resolve().parents[2]


def command(*args):
    return subprocess.run([sys.executable, '-B', '-m', 'vibeflow', *map(str,args)],
        env={**os.environ, 'PYTHONPATH':str(ROOT/'src')}, capture_output=True, text=True, timeout=180)


@pytest.mark.parametrize('target',['python','javascript'])
def test_review_publishes_html_and_json_without_graphics_runtime(tmp_path,target):
    if target == 'python':
        from tests.targets.python.test_code_plugins import executable_project
        workspace, config = executable_project(tmp_path/'project')
    else:
        from tests.targets.javascript.test_code_plugins import project
        workspace, config = project(tmp_path/'project')
    project_config = config.parent/'vibeflow_project.jsonc'
    settings=json.loads(project_config.read_text())
    settings['architecture']={'documents':[{'workflow':'workflow.jsonc','document':'ARCHITECTURE.jsonc'}]}
    project_config.write_text(json.dumps(settings))
    common=['--workspace',workspace.path,'--config',config]
    report=tmp_path/'report.json'
    for extra in (['--output',report],['--with-svg']):
        rejected=command('review',*common,*extra)
        assert rejected.returncode == 2, rejected.stdout+rejected.stderr
        assert 'unrecognized arguments' in rejected.stderr
        assert not report.exists()
        assert not (config.parent/'ARCHITECTURE.jsonc').exists()
    completed=command('review',*common,'--preview-root',tmp_path/'preview')
    assert completed.returncode == 0, completed.stdout+completed.stderr
    payload=json.loads(completed.stdout)
    assert payload['status'] in {'PASS','CONCERNS'}
    assert payload['published'] is True and payload['failed_stage'] is None
    assert Path(payload['preview']).is_file()
    assert payload['output'] == payload['preview']
    assert 'svg' not in payload
    assert (config.parent/'ARCHITECTURE.jsonc').read_text().startswith('// GENERATED BY VIBEFLOW')
    assert not list(tmp_path.rglob('*.svg'))
    mermaid=tmp_path/'workflow.mmd'
    for layout in ('default','review-columns'):
        exported=command('export-mermaid',*common,'--expand-nodesets','--mermaid-layout',layout,'--output',mermaid)
        assert exported.returncode == 0, exported.stdout+exported.stderr
        assert mermaid.read_text().startswith('flowchart ')
    repeated=command('review',*common,'--preview-root',tmp_path/'preview')
    assert repeated.returncode == 0, repeated.stdout+repeated.stderr
    assert json.loads(repeated.stdout)['preview_id'] != payload['preview_id']


@pytest.mark.parametrize('name',['export-svg','export-ascii','svg','ascii'])
def test_retired_commands_are_rejected_before_project_loading(name):
    result=command(name)
    assert result.returncode == 2
    assert 'unknown command' in result.stderr
